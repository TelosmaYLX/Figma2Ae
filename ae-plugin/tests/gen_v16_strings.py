def esc(text: str) -> str:
    out = []
    for b in text.encode("utf-8"):
        if 0x20 <= b < 0x7F and b not in (0x22, 0x5C):
            out.append(chr(b))
        elif b == 0x22:
            out.append('\\"')
        elif b == 0x5C:
            out.append("\\\\")
        else:
            out.append("\\x%02x" % b)
    return '"' + "".join(out) + '"'


