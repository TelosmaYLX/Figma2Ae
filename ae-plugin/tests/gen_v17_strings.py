def esc(text: str) -> str:
    """UTF-8 escape a string, splitting the literal where a \\xNN escape is
    followed by an ASCII hex digit (MSVC would otherwise swallow it, C7744)."""
    segments = []
    cur = []
    last_was_escape = False

    def flush():
        nonlocal cur
        if cur:
            segments.append('"' + "".join(cur) + '"')
            cur = []

    for b in text.encode("utf-8"):
        if 0x20 <= b < 0x7F and b not in (0x22, 0x5C):
            ch = chr(b)
            if last_was_escape and ch in "0123456789abcdefABCDEF":
                flush()
            cur.append(ch)
            last_was_escape = False
        elif b == 0x22:
            cur.append('\\"')
            last_was_escape = False
        elif b == 0x5C:
            cur.append("\\\\")
            last_was_escape = False
        else:
            cur.append("\\x%02x" % b)
            last_was_escape = True
    flush()
    return " ".join(segments) if segments else '""'


