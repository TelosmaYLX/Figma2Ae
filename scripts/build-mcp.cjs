'use strict';

const fs = require('node:fs/promises');
const path = require('node:path');
const {createHash} = require('node:crypto');
const esbuild = require('../mcp/node_modules/esbuild');
const root = path.resolve(__dirname, '..');
const mcp = path.join(root, 'mcp');
const vendor = path.join(mcp, 'vendor/cursor-talk-to-figma-mcp');
const figwright = path.join(mcp, 'vendor/figwright');
const sharedAlias = {'@figwright/shared':path.join(mcp,'src/figwright-shared.ts')};
const marker = '// BEGIN F2A MCP (generated by scripts/build-mcp.cjs)';

function between(source, from, to) {
  const start = source.indexOf(from), end = source.indexOf(to, start);
  if (start < 0 || end < 0) throw new Error('Upstream integration boundary changed: ' + from);
  return source.slice(start, end);
}

async function build() {
  const surehand = path.join(mcp, 'vendor/surehand');
  const {sha256} = require('../mcp/vendor/surehand/catalog.json');
  const hash = createHash('sha256').update(await fs.readFile(path.join(surehand, 'surehand-ae.mjs'))).digest('hex');
  if (hash !== sha256) throw new Error('Surehand bundle checksum does not match the tool catalog.');
  const upstream = await fs.readFile(path.join(vendor, 'server.ts'), 'utf8');
  const tools = between(upstream, '// Document Info Tool', '// Update the connectToFigma function') +
    between(upstream, '// Set Image Fill Tool', '// Update the join_channel tool');
  const entry = `
import {McpServer} from '@modelcontextprotocol/sdk/server/mcp.js';
import {StdioServerTransport} from '@modelcontextprotocol/sdk/server/stdio.js';
import {z} from 'zod';
import {readFile} from 'node:fs/promises';
import {status, selectSession, sendCommandToFigma} from './src/bridge.cjs';
import {ensureRelay} from './launcher.cjs';
import {registerLayerTools} from './src/layer-tools.ts';
import {registerFigwrightTools, withFigwrightArgs} from './src/figwright-tools.ts';
import {registerSurehandTools} from './src/surehand-tools.ts';
// Upstream helper logging must never enter the MCP stdout stream.
console.log = console.info = console.debug = (...args) => console.error(...args);
ensureRelay(error => {if (error) console.error('F2A MCP: ' + error.message);});
const instructions = [
  'For Figma tools, open F2A in Figma. A single open document connects automatically.',
  'Use get_f2a_status and join_channel to choose among multiple Figma documents.',
  'For After Effects, start with ae_status to check the current project and choose the intended instance.',
  'Use ae_list_comps and the composition item ID when editing F2A exports because folders can share composition names.',
  'Animate with ae_* tools and preview with ae_render_frame. Save an editable .aep with ae_save_project.',
  'For video, use an output module template installed in the target AE. Read available templates with ae_call and ae_list_render_queue when a queue item exists.',
  'Run ae_render_background and poll ae_render_jobs in the same session, or render in AE with ae_add_to_render_queue and ae_call for ae_render_queue_start.',
  'Discover more Surehand tools with ae_tools and ae_call.',
].join(' ');
const server = new McpServer({name:'F2A',version:'1.0.0'}, {instructions});
${tools.replace('- Always join the appropriate channel first with \\`join_channel()\\`', '- A single open F2A document connects automatically.')}
server.tool('get_f2a_status', 'List Figma documents with F2A open; a single document is selected automatically by other tools.', {}, async () => ({content:[{type:'text',text:JSON.stringify(await status())}]}));
server.tool('join_channel', 'Select an open F2A document by session ID, file key or unique name. Omit channel to select the only open document.', {channel:z.string().default('')}, async ({channel}) => {
  try { return {content:[{type:'text',text:JSON.stringify(await selectSession(channel))}]}; }
  catch(error) { return {isError:true,content:[{type:'text',text:error.message}]}; }
});
// F2A's own layer commands (group / ungroup / z-order / bulk rename / clip content / batch).
const send = withFigwrightArgs(sendCommandToFigma);
registerLayerTools(server, send);
registerFigwrightTools(server, send);
registerSurehandTools(server);
process.stdin.once('end', () => { void server.close(); });
server.connect(new StdioServerTransport()).catch(error => {console.error(error);process.exit(1);});
`;
  const settings = {absWorkingDir:root, bundle:true, platform:'node', target:'node20', format:'cjs', legalComments:'inline', metafile:true, external:['bufferutil','utf-8-validate']};
  const built = await esbuild.build({...settings, alias:sharedAlias, stdin:{contents:entry, loader:'ts', resolveDir:mcp, sourcefile:'f2a-server.ts'}, outfile:path.join(mcp,'server.cjs')});
  const relay = await esbuild.build({...settings, entryPoints:[path.join(mcp,'src/relay.cjs')], outfile:path.join(mcp,'relay.cjs')});

  const plugin = await fs.readFile(path.join(vendor,'plugin.js'),'utf8');
  const handlers = (between(plugin, '// Helper function for progress updates', '// Show UI') + plugin.slice(plugin.indexOf('// Handle commands from UI')))
    .replace(between(plugin, '// Initialize settings on load', 'function uniqBy'), '');
  // F2A layer commands are appended inside the same closure so they share `figma`, `handleCommand`
  // and the queue, and so upstream vendor/plugin.js stays unmodified.
  const layerCommands = await fs.readFile(path.join(mcp,'src/layer-commands.js'),'utf8');
  // The Figma sandbox scans comments for dynamic module syntax before parsing. Strip ordinary
  // dependency comments through esbuild's lexer. Licenses ship as separate files.
  const api = await esbuild.build({absWorkingDir:root, bundle:true, write:false, format:'iife', globalName:'F2AMCPBundle', target:'es2020', minifyWhitespace:true, legalComments:'none', metafile:true, alias:sharedAlias,
    stdin:{contents:`
import '../vendor/figwright/packages/plugin/src/shims.ts';
import {createFigwrightCommands, figwrightWrites, resumeHostYield} from './figwright-commands.ts';
const figwrightCommands = createFigwrightCommands(figma);
${handlers}
${layerCommands}
for (const name of figwrightWrites) F2A_BATCH_COMMANDS[name] = true;
export const execute = f2aExecute;
export const resume = resumeHostYield;
export const isWrite = command => !!F2A_BATCH_COMMANDS[command] || command === 'batch';
export const commands = Object.keys(figwrightCommands);
`, loader:'ts', resolveDir:path.join(mcp,'src'), sourcefile:'f2a-plugin.ts'}});
  const pluginFile = path.join(root,'figma-plugin/code.js');
  const current = await fs.readFile(pluginFile,'utf8');
  const figwrightLicense = await fs.readFile(path.join(figwright,'LICENSE'),'utf8');
  await fs.writeFile(pluginFile, current.split(marker)[0].trimEnd() + '\n\n' + marker + '\n' + api.outputFiles[0].text + '\nvar F2AMCP = {execute:F2AMCPBundle.execute, resume:F2AMCPBundle.resume, isWrite:F2AMCPBundle.isWrite, commands:F2AMCPBundle.commands};\n');

  const packageDirs = new Set();
  for (const input of [...Object.keys(built.metafile.inputs), ...Object.keys(relay.metafile.inputs), ...Object.keys(api.metafile.inputs)]) {
    let directory = path.dirname(path.resolve(root,input));
    while (directory.includes('node_modules')) {
      try { await fs.access(path.join(directory,'package.json')); packageDirs.add(directory); break; } catch {}
      directory = path.dirname(directory);
    }
  }
  const licenses = ['Figwright 0.7.0 (031df6a01e103c7adcc01e63d6d8aab0990001e8)\n' + figwrightLicense];
  for (const directory of [...packageDirs].sort()) {
    const pkg = JSON.parse(await fs.readFile(path.join(directory,'package.json'),'utf8'));
    const files = (await fs.readdir(directory)).filter(name => /^(licen[cs]e|copying|notice)(\.|$)/i.test(name));
    for (const file of files) licenses.push(`${pkg.name} ${pkg.version}\n${await fs.readFile(path.join(directory,file),'utf8')}`);
  }
  await fs.writeFile(path.join(mcp,'THIRD_PARTY_LICENSES.txt'), licenses.join('\n\n--------------------\n\n'));
  console.log('Built F2A MCP server with Surehand, relay and embedded Figma commands.');
}

build().catch(error => {console.error(error);process.exitCode=1;});
