'use strict';

const fs = require('node:fs');
const path = require('node:path');
const { detectImageExt, readImageDimensions, resolveShadowBaseNode } = require('./png.cjs');

const CODE_PATH = path.resolve(__dirname, '../figma-plugin/code.js');
const MCP_MARKER = '// BEGIN F2A MCP (generated by scripts/build-mcp.cjs)';
const IMAGE_CHUNK_SIZE = 1024 * 1024;

let cachedCode = null;
let cachedMtimeMs = 0;

function loadCodeSlices() {
  const stat = fs.statSync(CODE_PATH);
  if (!cachedCode || stat.mtimeMs !== cachedMtimeMs) {
    const full = fs.readFileSync(CODE_PATH, 'utf8');
    const idx = full.indexOf(MCP_MARKER);
    cachedCode = {
      full,
      core: idx >= 0 ? full.slice(0, idx) : full,
    };
    cachedMtimeMs = stat.mtimeMs;
  }
  return cachedCode;
}

function buildEvalScript(bodySource, { includeMcp = false, selectionIds = null, workspacePlugin = false, fileKey = null } = {}) {
  const slices = loadCodeSlices();
  const pluginSource = includeMcp ? slices.full : slices.core;
  const configJson = JSON.stringify({
    selectionIds: Array.isArray(selectionIds) ? selectionIds : null,
    workspacePlugin: !!workspacePlugin,
    fileKey: fileKey || null,
  });

  return [
    'return (async () => {',
    'const __f2aOrigFigma = figma;',
    'const __f2aConfig = ' + configJson + ';',
    'const __f2aMessages = [];',
    'const __f2aUi = {',
    '  onmessage: null,',
    '  postMessage(msg) {',
    '    if (msg && msg.tag === "@figwright/yield" && msg.kind === "yield-request") {',
    '      const resume = { tag: msg.tag, kind: "yield-resume", id: msg.id, background: false };',
    '      Promise.resolve().then(() => { if (typeof __f2aUi.onmessage === "function") __f2aUi.onmessage(resume); });',
    '      return;',
    '    }',
    '    __f2aMessages.push(msg);',
    '  }',
    '};',
    'const __f2aOverrides = {',
    '  ui: __f2aUi,',
    '  showUI() {},',
    '  on() {},',
    '  off() {},',
    '  once() {},',
    '  notify() { return { cancel() {} }; },',
    '  closePlugin() {},',
    '  commitUndo() {},',
    '  pluginId: __f2aConfig.workspacePlugin ? "f2a-ship-to-ae-workspace" : "f2a-ship-to-ae",',
    '  fileKey: __f2aConfig.fileKey,',
    '  editorType: "figma",',
    '  clientStorage: { async getAsync() { return null; }, async setAsync() {} }',
    '};',
    'const __f2aFigma = new Proxy(__f2aOrigFigma, {',
    '  get(target, prop) {',
    '    if (Object.prototype.hasOwnProperty.call(__f2aOverrides, prop)) return __f2aOverrides[prop];',
    '    const value = target[prop];',
    '    return typeof value === "function" ? value.bind(target) : value;',
    '  },',
    '  set(target, prop, value) {',
    '    if (Object.prototype.hasOwnProperty.call(__f2aOverrides, prop)) { __f2aOverrides[prop] = value; return true; }',
    '    target[prop] = value;',
    '    return true;',
    '  },',
    '  has(target, prop) {',
    '    return Object.prototype.hasOwnProperty.call(__f2aOverrides, prop) || (prop in target);',
    '  }',
    '});',
    'const __f2aSelectionNodes = [];',
    'if (__f2aConfig.selectionIds && __f2aConfig.selectionIds.length) {',
    '  for (const __id of __f2aConfig.selectionIds) {',
    '    const __n = await __f2aOrigFigma.getNodeByIdAsync(__id);',
    '    if (__n && !__n.removed) __f2aSelectionNodes.push(__n);',
    '  }',
    '  try { __f2aOrigFigma.currentPage.selection = __f2aSelectionNodes; } catch {}',
    '}',
    'return await (async function (figma, __html__) {',
    pluginSource,
    bodySource,
    '})(__f2aFigma, "");',
    '})();',
  ].join('\n');
}

function hydrateDeferredImage(deferred, fetched) {
  const b64 = fetched.b64 || '';
  const bytes = Buffer.from(b64, 'base64');
  const ext = detectImageExt(bytes);
  let natW = fetched.size && fetched.size.width ? fetched.size.width : 0;
  let natH = fetched.size && fetched.size.height ? fetched.size.height : 0;
  if (!(natW > 0 && natH > 0)) {
    const dims = readImageDimensions(bytes);
    if (dims) {
      natW = dims.width || 0;
      natH = dims.height || 0;
    }
  }
  const meta = { ...deferred.meta, ext, natW, natH };
  if (meta.imageFilters) {
    if (
      meta.scaleMode === 'FILL' &&
      meta.matte &&
      meta.matte.kind === 'rect' &&
      !meta.matte.r &&
      natW > 0 &&
      natH > 0 &&
      Math.abs(meta.cw - (meta.ch * natW) / natH) < 0.00001
    ) {
      meta.matte = null;
    }
  }
  if (deferred.bicubicExport && !(deferred.preserveSource && !deferred.rasterScale)) {
    const scale = deferred.exportRasterScale || 1;
    const factor = deferred.rasterScale
      ? 0.5
      : scale * (meta.scaleMode === 'FIT'
        ? Math.min(meta.cw / natW, meta.ch / natH)
        : Math.max(meta.cw / natW, meta.ch / natH));
    meta.bicubic = {
      width: Math.max(1, Math.ceil(natW * factor)),
      height: Math.max(1, Math.ceil(natH * factor)),
    };
  }
  return { meta, data: b64 };
}

function emitImageChunks(images, commandId, emit) {
  for (let i = 0; i < images.length; i++) {
    const item = images[i];
    const b64 = item.data || '';
    const parts = Math.max(1, Math.ceil(b64.length / IMAGE_CHUNK_SIZE));
    for (let seq = 0; seq < parts; seq++) {
      emit({
        type: 'image-chunk',
        index: i,
        total: images.length,
        exportCommandId: commandId || undefined,
        seq,
        parts,
        meta: seq === 0 ? item.meta : null,
        dataPart: b64.slice(seq * IMAGE_CHUNK_SIZE, (seq + 1) * IMAGE_CHUNK_SIZE),
      });
      if (commandId) emit({ type: 'command_progress', commandId });
    }
  }
}

function assembleImagesFromMessages(messages) {
  const assembled = [];
  const inProgress = new Map();
  for (const msg of messages) {
    if (msg.type === 'image-chunk') {
      if (msg.seq === 0) {
        inProgress.set(msg.index, { meta: msg.meta, parts: [] });
      }
      const entry = inProgress.get(msg.index);
      if (!entry) continue;
      entry.parts.push(msg.dataPart || '');
      if (msg.seq === msg.parts - 1) {
        assembled.push({ index: msg.index, kind: 'ready', meta: entry.meta, data: entry.parts.join('') });
        inProgress.delete(msg.index);
      }
    } else if (msg.type === 'image-deferred') {
      assembled.push({ index: msg.index, kind: 'deferred', deferred: msg });
    }
  }
  assembled.sort((a, b) => a.index - b.index);
  return assembled;
}

function createRunner(client, runnerOptions = {}) {
  const workspacePlugin = !!runnerOptions.workspacePlugin;

  async function resolveSelectionIds(target, explicitIds) {
    if (Array.isArray(explicitIds) && explicitIds.length) {
      return { ids: explicitIds.slice(), target };
    }
    const { result, target: resolvedTarget } = await client.getSelection(target);
    const items = Array.isArray(result) ? result : [];
    const effectiveTarget = resolvedTarget
      ? { documentId: resolvedTarget.documentId, pageId: resolvedTarget.pageId }
      : target;
    return {
      ids: items.map(item => item.id).filter(Boolean),
      items,
      target: effectiveTarget,
    };
  }

  async function fetchImageByHash(hash, target) {
    const code = [
      'return (async () => {',
      'const img = figma.getImageByHash(' + JSON.stringify(hash) + ');',
      'if (!img) throw new Error("图片素材缺失：" + ' + JSON.stringify(hash) + ');',
      'const bytes = await img.getBytesAsync();',
      'let size = null;',
      'try { size = await img.getSizeAsync(); } catch {}',
      'return { b64: figma.base64Encode(bytes), size };',
      '})();',
    ].join('\n');
    const { result } = await client.evalCode(code, target);
    return result;
  }

  async function exportReference(nodeId, origin, rasterOrigin, rasterScale, bicubicExport, target) {
    const body = 'return await _exportReferenceNode(' +
      JSON.stringify(nodeId) + ', ' +
      JSON.stringify(origin) + ', ' +
      JSON.stringify(rasterOrigin) + ', ' +
      JSON.stringify(rasterScale) + ', ' +
      JSON.stringify(!!bicubicExport) + ');';
    const script = buildEvalScript(body, { workspacePlugin });
    const { result } = await client.evalCode(script, target);
    return result;
  }

  async function exportSelection(settings = {}, target = {}, hooks = {}) {
    const onMessage = typeof hooks.onMessage === 'function' ? hooks.onMessage : () => {};
    const onProgress = typeof hooks.onProgress === 'function' ? hooks.onProgress : () => {};
    const commandId = hooks.commandId;
    const includeReferences = settings.skipReferences !== true;
    const resolveHeadlessShadows = hooks.resolveHeadlessShadows === true;

    const emit = msg => onMessage(msg);
    emit({ type: 'export-state', busy: true });

    try {
      const sel = await resolveSelectionIds(target, settings.selectionIds);
      if (!sel.ids.length) {
        const errMsg = '请至少选择一个图层或画框。';
        emit({ type: 'error', message: errMsg, nodeId: null });
        if (hooks.throwOnError) {
          const err = new Error(errMsg);
          err.nodeId = null;
          throw err;
        }
        return null;
      }

      const effectiveTarget = sel.target || target;
      const exportOpts = {
        ...settings,
        selectionIds: sel.ids,
        skipReferences: true,
        deferHashImages: true,
      };
      onProgress('正在提取图层结构…');
      emit({ type: 'progress', message: '正在从 OpenPencil 提取图层结构…' });

      const body = [
        'const opts = ' + JSON.stringify(exportOpts) + ';',
        'await exportSelectionSVG(',
        '  opts.useNodes !== false,',
        '  !!opts.organize,',
        '  opts.ignoreHidden !== false,',
        '  opts.convertMasks !== false,',
        '  opts.rasterGroups !== false,',
        '  opts.rasterTexts === true,',
        '  opts,',
        '  ' + JSON.stringify(commandId || null) + ' || undefined',
        ');',
        'return __f2aMessages;',
      ].join('\n');

      const script = buildEvalScript(body, {
        workspacePlugin,
        selectionIds: sel.ids,
        fileKey: effectiveTarget && effectiveTarget.documentId ? 'openpencil:' + effectiveTarget.documentId : null,
      });

      const { result: stage1Messages } = await client.evalCode(script, effectiveTarget);
      const msgs = Array.isArray(stage1Messages) ? stage1Messages : [];

      const errorMsg = msgs.find(m => m && m.type === 'error');
      const shipMsg = msgs.find(m => m && m.type === 'ship');
      if (errorMsg || !shipMsg) {
        const message = (errorMsg && errorMsg.message) || 'OpenPencil 导出失败：未收到导出数据包。';
        const nodeId = (errorMsg && errorMsg.nodeId) || null;
        emit({ type: 'error', message, nodeId });
        if (hooks.throwOnError) {
          const err = new Error(message);
          err.nodeId = nodeId;
          throw err;
        }
        return null;
      }

      const rawImages = assembleImagesFromMessages(msgs);
      const uniqueHashes = [];
      const seenHashes = new Set();
      for (const entry of rawImages) {
        if (entry.kind === 'deferred' && entry.deferred.hash && !seenHashes.has(entry.deferred.hash)) {
          seenHashes.add(entry.deferred.hash);
          uniqueHashes.push(entry.deferred.hash);
        }
      }

      const hashCache = new Map();
      for (let hi = 0; hi < uniqueHashes.length; hi++) {
        const hash = uniqueHashes[hi];
        const status = '正在读取原图素材 ' + (hi + 1) + '/' + uniqueHashes.length + '…';
        onProgress(status);
        emit({ type: 'progress', message: status });
        if (commandId) emit({ type: 'command_progress', commandId });
        const fetched = await fetchImageByHash(hash, effectiveTarget);
        hashCache.set(hash, fetched);
      }

      const finalImages = [];
      for (const entry of rawImages) {
        if (entry.kind === 'ready') {
          finalImages.push({ meta: entry.meta, data: entry.data });
        } else if (entry.kind === 'deferred') {
          const fetched = hashCache.get(entry.deferred.hash);
          if (!fetched) {
            throw new Error('图片「' + (entry.deferred.meta?.name || '') + '」读取失败');
          }
          finalImages.push(hydrateDeferredImage(entry.deferred, fetched));
        }
      }

      const referenceIds = Array.isArray(shipMsg.referenceIds) ? shipMsg.referenceIds : sel.ids;
      if (includeReferences && referenceIds.length) {
        const rasterScale = settings.rasterScale == null ? 1 : Number(settings.rasterScale);
        const bicubicExport = settings.bicubicExport === true;
        for (let ri = 0; ri < referenceIds.length; ri++) {
          const status = '正在渲染原图对照 ' + (ri + 1) + '/' + referenceIds.length + '…';
          onProgress(status);
          emit({ type: 'progress', message: status });
          if (commandId) emit({ type: 'command_progress', commandId });
          const refImg = await exportReference(
            referenceIds[ri],
            shipMsg.nodeOrigin,
            shipMsg.rasterOrigin,
            rasterScale,
            bicubicExport,
            effectiveTarget
          );
          if (refImg && refImg.meta) {
            finalImages.push(refImg);
          }
        }
      }

      if (resolveHeadlessShadows) {
        for (const item of finalImages) {
          if (item.meta && item.meta.shadowBase) {
            item.data = resolveShadowBaseNode(item.data, item.meta.shadowBase);
            item.meta.shadowBase = null;
          }
        }
      }

      const cleanShip = { ...shipMsg };
      delete cleanShip.referenceIds;
      delete cleanShip.rasterOrigin;
      cleanShip.imageCount = finalImages.length;

      emit(cleanShip);
      emitImageChunks(finalImages, commandId, emit);
      if (finalImages.length) {
        emit({ type: 'images-done', exportCommandId: commandId || undefined });
      }

      const packet = {
        name: cleanShip.name,
        frame: cleanShip.frame,
        svg: cleanShip.svg,
        nodes: cleanShip.nodes,
        texts: cleanShip.texts,
        effects: cleanShip.effects,
        shift: cleanShip.shift,
        containers: cleanShip.containers,
        organize: cleanShip.organize,
        preserveImageFilters: cleanShip.preserveImageFilters === true,
        preserveBackgroundBlur: cleanShip.preserveBackgroundBlur === true,
        imageCount: finalImages.length,
        images: finalImages.map(item => ({ ...item.meta, data: item.data })),
        newComp: cleanShip.newComp,
        vnStats: cleanShip.vnStats,
        blendStats: cleanShip.blendStats,
      };
      return { ship: cleanShip, packet };
    } catch (error) {
      const message = error && error.message ? error.message : String(error);
      const nodeId = error && error.nodeId ? error.nodeId : null;
      emit({ type: 'error', message, nodeId });
      if (hooks.throwOnError) throw error;
      return null;
    } finally {
      emit({ type: 'export-state', busy: false });
    }
  }

  async function markRaster(mark, target = {}) {
    const sel = await resolveSelectionIds(target);
    const body = [
      'markRasterSelection(' + JSON.stringify(!!mark) + ');',
      'return __f2aMessages;',
    ].join('\n');
    const script = buildEvalScript(body, { workspacePlugin, selectionIds: sel.ids });
    const { result } = await client.evalCode(script, sel.target || target);
    return Array.isArray(result) ? result : [];
  }

  async function markRoot(mark, target = {}) {
    const sel = await resolveSelectionIds(target);
    const body = [
      'markRootSelection(' + JSON.stringify(!!mark) + ');',
      'return __f2aMessages;',
    ].join('\n');
    const script = buildEvalScript(body, { workspacePlugin, selectionIds: sel.ids });
    const { result } = await client.evalCode(script, sel.target || target);
    return Array.isArray(result) ? result : [];
  }

  async function runLayerTool(action, target = {}) {
    const sel = await resolveSelectionIds(target);
    const body = [
      'runLayerTool(' + JSON.stringify(action) + ');',
      'return { messages: __f2aMessages, nextSelectionIds: (__f2aOrigFigma.currentPage.selection || []).map(n => n.id) };',
    ].join('\n');
    const script = buildEvalScript(body, { workspacePlugin, selectionIds: sel.ids });
    const { result } = await client.evalCode(script, sel.target || target);
    const effectiveTarget = sel.target || target;
    if (result && Array.isArray(result.nextSelectionIds) && result.nextSelectionIds.length) {
      try {
        await client.callTool('set_selection', { ids: result.nextSelectionIds }, effectiveTarget);
      } catch {}
    }
    return (result && Array.isArray(result.messages)) ? result.messages : [];
  }

  async function locateLayer(nodeId, target = {}) {
    if (!nodeId) return { type: 'locate-result', ok: false, message: '定位失败：缺少图层 ID。' };
    try {
      const findCode = [
        'return (async () => {',
        'const targetNode = await figma.getNodeByIdAsync(' + JSON.stringify(nodeId) + ');',
        'if (!targetNode || targetNode.removed) throw new Error("图层已删除或不存在。");',
        'let page = targetNode.parent;',
        'while (page && page.type !== "PAGE") page = page.parent;',
        'if (!page) throw new Error("该图层不在画布中。");',
        'return { id: targetNode.id, pageId: page.id };',
        '})();',
      ].join('\n');
      const { result: found, target: resolvedTarget } = await client.evalCode(findCode, target);
      const docTarget = {
        documentId: (resolvedTarget && resolvedTarget.documentId) || target.documentId,
        pageId: found.pageId,
      };
      if (docTarget.documentId) {
        try { await client.activateDocument(docTarget); } catch {}
      }
      try { await client.callTool('set_selection', { ids: [found.id] }, docTarget); } catch {}
      try { await client.callTool('zoom_to_fit', { ids: [found.id] }, docTarget); } catch {}
      return { type: 'locate-result', ok: true };
    } catch (error) {
      return { type: 'locate-result', ok: false, message: '定位失败：' + (error.message || error) };
    }
  }

  async function executeMcpCommand(command, params = {}, target = {}, hooks = {}) {
    const onMessage = typeof hooks.onMessage === 'function' ? hooks.onMessage : () => {};
    const commandId = hooks.commandId;
    if (command === 'f2a_export_aep') {
      const exportParams = {
        useNodes: true,
        organize: !!params.organize,
        ignoreHidden: params.ignoreHidden !== false,
        convertMasks: true,
        rasterGroups: true,
        rasterTexts: params.rasterTexts === true,
        ...params,
        target: 'aep',
      };
      return exportSelection(exportParams, target, {
        onMessage,
        onProgress: hooks.onProgress,
        commandId,
        resolveHeadlessShadows: hooks.resolveHeadlessShadows === true,
        throwOnError: hooks.throwOnError === true,
      });
    }

    const sel = await resolveSelectionIds(target);
    const effectiveTarget = sel.target || target;
    const body = [
      'const __cmd = ' + JSON.stringify(command) + ';',
      'const __params = ' + JSON.stringify(params || {}) + ';',
      'const __beforeSel = (__f2aOrigFigma.currentPage.selection || []).map(n => n.id);',
      'const __res = await F2AMCP.execute(__cmd, __params);',
      'const __afterSel = (__f2aOrigFigma.currentPage.selection || []).map(n => n.id);',
      'return { result: __res, selectionChanged: JSON.stringify(__beforeSel) !== JSON.stringify(__afterSel), nextSelectionIds: __afterSel };',
    ].join('\n');

    const script = buildEvalScript(body, {
      includeMcp: true,
      workspacePlugin,
      selectionIds: sel.ids,
      fileKey: effectiveTarget && effectiveTarget.documentId ? 'openpencil:' + effectiveTarget.documentId : null,
    });
    const { result } = await client.evalCode(script, effectiveTarget);
    if (result && result.selectionChanged && Array.isArray(result.nextSelectionIds)) {
      try {
        await client.callTool('set_selection', { ids: result.nextSelectionIds }, effectiveTarget);
      } catch {}
    }
    return result ? result.result : null;
  }

  return {
    exportSelection,
    markRaster,
    markRoot,
    runLayerTool,
    locateLayer,
    executeMcpCommand,
    fetchImageByHash,
    exportReference,
  };
}

module.exports = {
  CODE_PATH,
  loadCodeSlices,
  buildEvalScript,
  hydrateDeferredImage,
  assembleImagesFromMessages,
  createRunner,
};
