const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const root = path.join(__dirname, '..');
let depth = 0, begins = 0, ends = 0;
class CompItem { constructor(id = 1) { this.id = id; this.layers = {}; this.numLayers = 0; } openInViewer() { app.project.activeItem = this; } }
const comp = new CompItem();
const files = {job: JSON.stringify({nodesPath: 'nodes', containersPath: 'groups'}), nodes: '[]', groups: '[]'};
function File(name) { this.exists = name in files; this.open = () => {}; this.close = () => {}; this.read = () => files[name]; }
const app = {project: {activeItem: comp}, beginUndoGroup() { assert.equal(depth, 0, 'Native undo groups must not nest'); depth++; begins++; }, endUndoGroup() { assert.equal(depth, 1); depth--; ends++; }};
const context = vm.createContext({app, CompItem, File, SVGParser: {fromNodes() { return {shapes: []}; }}});
vm.runInContext(fs.readFileSync(path.join(root, 'host/figma/aeShapeBuilder.jsx'), 'utf8'), context);
vm.runInContext(fs.readFileSync(path.join(root, 'host/figma/figmaRunner.jsx'), 'utf8'), context);
const builder = context.AEShapeBuilder;
assert.equal(builder.withUndo('outer', () => builder.withUndo('inner', () => 42)), 42);
assert.equal(begins, 1); assert.equal(ends, 1);
assert.throws(() => builder.withUndo('outer', () => builder.withUndo('inner', () => { throw new Error('forced'); })), /forced/);
assert.equal(depth, 0); assert.equal(begins, 2); assert.equal(ends, 2);
assert.equal(builder.withUndo('after failure', () => 7), 7);
assert.equal(depth, 0);
let before = begins;
assert.doesNotMatch(context.runImportBatch('job'), /error/i);
assert.equal(begins - before, 1); assert.equal(depth, 0); assert.equal(begins, ends);
context.SVGParser.fromNodes = () => { throw new Error('forced parser failure'); };
before = begins;
assert.match(context.runImportBatch('job'), /forced parser failure/);
assert.equal(begins - before, 1); assert.equal(depth, 0); assert.equal(begins, ends); assert.equal(context._mkContainers, null);
context.SVGParser.fromNodes = () => ({shapes: []});
files.groups = '[{"id":"group"}]';
builder.organize = () => { throw new Error('forced organize failure'); };
before = begins;
assert.match(context.runImportBatch('job'), /forced organize failure/);
assert.equal(begins - before, 1); assert.equal(depth, 0); assert.equal(begins, ends); assert.equal(context._mkContainers, null);
files.groups = '[]';
const target = new CompItem(101);
app.project.numItems = 1; app.project.item = () => target;
files.job = JSON.stringify({nodesPath: 'nodes', containersPath: 'groups', compId: 101});
assert.doesNotMatch(context.runImportBatch('job'), /error/i); assert.equal(app.project.activeItem, target);
files.job = JSON.stringify({compId: 999}); before = begins;
assert.match(context.runImportBatch('job'), /ERROR/); assert.equal(begins, before, 'A missing target must not open an undo group');
console.log('PASS: one owner, nested builders, exception balance, next import, parser/organize failures, flat import');
